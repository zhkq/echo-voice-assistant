package com.echo.contact.ui

/**
 * **App 内标题**（用户 2026-10-18 中午定的名字：*"app 的名字改成 ECHO 超级助理"*）。
 *
 * ## ⚠️ 从 2026-10-19 晚起，这个常量**有意**与桌面名不同值
 *
 *  * **桌面/启动器显示名** = `res/values/strings.xml` 的 `app_name` = `超级助理`
 *    （`AndroidManifest.xml` 的 `android:label` 指向它；系统设置里的应用名、
 *    **通知头部的应用名**也都读它）；
 *  * 这里 [APP_TITLE] = `ECHO 超级助理`，只用于**App 内自己画的**那几处
 *    （首页顶部那张卡、配对页标题、设置页"关于"那一行）。
 *
 * 为什么会有这个差别（用户 2026-10-19 晚原话：*"因为 app logo 已经有 echo 了"*）：
 * 桌面图标本身就是 ECHO 品牌位，名字里再写一遍 "ECHO"，用户看到的就是"ECHO 写了两次"；
 * 而进了 App 之后没有图标陪着，标题就得自己把品牌带上。所以这**不是**漏改的一处，
 * 是两处各管一段 —— 别哪天又"统一"回去。判据见 `AppNameTest`。
 *
 * ## 为什么要有一个常量，而不是到处写字符串
 *
 * App 内的标题会出现在好几处（主页顶部那张卡、配对页标题、设置页"关于"那一行）。
 * 四处各写一份，迟早只改到其中一处 —— 于是同一版 App 里几个页面显示的名字不一样。
 * 所以 App 内**只**用 [APP_TITLE]（界面里不许再写死一份字符串）。
 *
 * ## 为什么改名字不改包名
 *
 * `applicationId` / `namespace` 一个字都没动（还是 `com.echo.contact`）：
 * 改包名 = 换一个 App —— 手机上会**多出一个图标**（旧的那个还在），
 * 而配对凭据、本地录音清单（`MeetingDraftStore` 的 app 私有目录）都绑在旧包上，
 * 用户升级完会发现"配对没了、录的音也不见了"。名字是给人看的，包名是给系统认的，
 * 这两件事不能一起改。
 */
internal const val APP_TITLE = "ECHO 超级助理"
