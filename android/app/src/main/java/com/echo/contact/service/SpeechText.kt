package com.echo.contact.service

/**
 * 念之前的**文本归一化**（只改"念出来的那串"，屏幕上的原文一个字都不动）。
 *
 * ## 为什么要有它（用户 2026-10-18 傍晚的原话）
 *
 * > *"朗读气温的时候 8-19 度，总被念成 819 度，这个有修复的可能吗"*
 *
 * 有 —— 而且问题不在数据、在**念法**：手机的系统 TTS（以及 ECHO 的 `/api/tts`）拿到
 * `8-19` 会把那个连字符当"负号 / 连接符"吞掉，于是"八到十九度"被念成"八百一十九度"。
 * 屏幕上该显示的还是 `8-19 度`（用户要看的也是它），只有**送去合成的那串**要换成
 * "8 到 19 度"。
 *
 * ## ⚠️ 2026-10-18 夜里查实的边界：**这个类修不了"819 度"那一例**
 *
 * 用户当天 20:59/21:00 实测仍然是"819 度"。翻电脑上的真凭据（`D:\ECHO\data\echo.db`
 * 的 `commands.brief`）发现：**念出去的那串里，那个范围符号在到达手机之前就已经没了** ——
 *
 * ```
 * reply: 明天（10月19日）北京天气晴转多云，气温 8~19℃，白天南风…
 * brief: 北京明天（10月19日）晴转多云，819度，微风无雨…      ← 手机上念的就是这个
 * ```
 *
 * 抹掉它的不是手机：`app/assistant.py::_clean_line()`（第 219 行 `re.sub(r"[_~^]", "", t)`）
 * 把 `~` 当 markdown 强调符删了，第 221 行又把 `℃` 换成 `度` —— 于是 `8~19℃` 变成 `819度`。
 * **`819` 与一个真的八百一十九是不可区分的**，所以手机侧无论怎么归一化都救不回来
 * （也不该去"猜"：猜错就是把正常数字念坏）。真正的修法在 `app/assistant.py`（服务端简报生成），
 * 不在本文件；本文件只管**还带着分隔符**的那些文本。
 *
 * 那还有用吗？有 —— 手机收到的文本里至少还有两条路是**带分隔符的原样文本**：
 *
 *  1. **老电脑的退路**：没有 `speakText` 时，`SpeakPlan.summaryOf()` 在手机上从 `reply`
 *     现切摘要（reply 里的 `8~19℃` 是原样的）→ 送进本类就能念对；
 *  2. **每日回顾播报**：`brief` 来自技能的【播报】原文（`app/daily_review.py` 直接落库，
 *     不过 `_clean_line`），同样带着 `~` / `℃`。
 *
 * ## 规则边界（写死在 [RANGE]/[RANGE_WITH_UNITS] 里，`SpeechTextTest` 逐条钉住）
 *
 * 只有**同时**满足下面三条才改：
 *
 *  1. 左右各是一个**无符号**数字（整数或小数；**全角数字也认**：`８-１９度`）；
 *  2. 中间是区间分隔符之一：`-`、`－`（全角）、`—`（破折号）、`–`（短破折号）、
 *     `~`、`～`（全角），两边可以有空格；**`至` 不在此列**（`8至19度` 本来就是"到"的念法，
 *     再改就成了"8 到 19"，是改坏）；
 *  3. 右数字**后面跟着一个区间单位**（中间可以有空格）：`度`、`摄氏度`、`℃`、`°C`、`°F`、
 *     `°`、`%`（`％`）、`km`、`公里`、`千米`。
 *
 * 第 ③ 条是"别过度归一化"的关键 —— 它把日期与版本号挡在外面（这些**故意不改**）：
 *
 *  * `10-18`、`2026-10-18`：后面没有单位，是**日期**；念成"10 到 18"反而是错的；
 *  * `v2.1.7`、`2.1.7`：根本没有区间分隔符；
 *  * `-5 度`、`最低-5度`：左边没有数字（负号不是数字）→ 不动；
 *    连 `-5-3度` 这种"负数区间"也不动（左数字紧跟 `-`，被 `(?<!...)` 挡住）：
 *    **宁可少改，也不要把零下温度念错**。
 *
 * ## 为什么只替换"左数字 分隔符 右数字"这一小段
 *
 * 单位**不消费**（只用作前瞻断言），所以 `8 - 19 ℃` → `8 到 19 ℃`：
 * 原来那个空格、单位、以及单位后面的字（"度左右"、"% 以上"）一个字节都不动。
 * 把单位一起吃掉再拼回去，迟早会把某种写法拼坏。
 *
 * 唯一**必须**吃掉单位的写法是"两端都带单位"（`8度-19度`）—— 那种句子中间那个 `-`
 * 被两个 `度` 夹着，不吃单位就根本匹配不到。它由 [RANGE_WITH_UNITS] 单独处理，
 * 而且**先**跑：处理完那种写法后，剩下的文本里就不会再有"数字 度 分隔符"这种形状了。
 *
 * ## 为什么必须幂等
 *
 * 调用点不止一处（界面朗读入口一次、系统 TTS 引擎入口再兜一次 —— 见那些地方的注释）。
 * 同一条文本被归一化两遍也只能得到同一个结果，绝不能出现"8 到 到 19"。
 * 这一点由 `SpeechTextTest` 用"套两遍 == 套一遍"钉住。
 */
internal object SpeechText {

    /** 半角 + **全角**数字（`８-１９度` 这种从中文输入法里出来的写法见过）。 */
    private const val DIGITS = "0-9０-９"

    /** 一个有符号数字：`8`、`8.5`、`８.５`。 */
    private const val NUM = "(?:[$DIGITS]+(?:\\.[$DIGITS]+)?)"

    /**
     * 区间分隔符。
     *
     * **刻意不含 `至`**：`8至19度` 已经是"八至十九度"的正确念法，再换成"到"是多此一举
     * （而且会让"至"这个字从原文里消失）。
     */
    private const val SEP = "[-－—–~～]"

    /**
     * 区间单位白名单（见类注释第 ③ 条）。
     *
     * 长的写在前面（`摄氏度` 在 `度` 前、`°C` 在 `°` 前）：这里是前瞻（不消费），
     * 短的那个先匹配会让 `C` 留在原文里 —— 结果其实一样，只是把长的写前面更不容易读错。
     */
    private const val UNIT = "(?:摄氏度|℃|°C|°F|公里|千米|度|%|％|°|[kK][mM])"

    /**
     * 左边界：左数字**不许**紧跟在这些字符后面。
     *
     * 这样 `2026-10-18`、`-5-3` 都不会被从中间切一刀（见类注释第 ② 条）。
     */
    private const val LEFT = "(?<![$DIGITS.\\-－—–~～])"

    /**
     * 「数字 + 分隔符 + 数字 +（紧跟单位）」—— 单位只当前瞻、**不消费**。
     */
    private val RANGE = Regex(
        LEFT +
            "($NUM)" +
            "\\s*$SEP\\s*" +
            "($NUM)" +
            "(?=\\s*$UNIT)"
    )

    /**
     * 「数字 + 单位 + 分隔符 + 数字 + 单位」（`8度-19度`、`8℃～19℃`、`8 摄氏度 - 19 摄氏度`）。
     *
     * 为什么这个**必须**吃掉单位：中间那个分隔符被两个单位夹着，`RANGE` 的左数字后面紧跟的是
     * 单位而不是分隔符，匹配不到；而用户明确点过这一种写法（*"范围两端带单位（8度-19度）
     * 也应念成'8 度到 19 度'"*）。它排在 [RANGE] 之前跑。
     */
    private val RANGE_WITH_UNITS = Regex(
        LEFT +
            "($NUM)" +
            "(\\s*$UNIT)\\s*$SEP\\s*" +
            "($NUM)" +
            "(\\s*$UNIT)"
    )

    /**
     * 把 [text] 里的数字区间换成"「到」"的念法；其余字节原样返回（**幂等**）。
     *
     * 空串原样返回（`Regex.replace` 对空串本来也无事，这里只是省一次构造）。
     */
    fun normalize(text: String): String {
        if (text.isEmpty()) return text
        // ① 两端都带单位的（要吃单位）
        val withUnits = RANGE_WITH_UNITS.replace(text) { m ->
            // 两端的单位**各自照抄**（`8度-19℃` 这种混写也要一字不差地留下来）
            val left = halfWidthDigits(m.groupValues[1])
            val leftUnit = m.groupValues[2].trim()
            val right = halfWidthDigits(m.groupValues[3])
            val rightUnit = m.groupValues[4].trim()
            // ⚠️ 这里的 `${leftUnit}` 必须带花括号：Kotlin 的标识符允许中文字符，
            // 写成 `$leftUnit到` 会被当成一个叫 `leftUnit到` 的变量（编译期就报未解析）。
            "$left ${leftUnit}到 $right $rightUnit"
        }
        // ② 只有右端带单位的（单位不消费，原样留着）
        return RANGE.replace(withUnits) { m ->
            "${halfWidthDigits(m.groupValues[1])} 到 ${halfWidthDigits(m.groupValues[2])}"
        }
    }

    /** 这段文本里有没有"会被改"的区间（用例与排查用；只读，不改文本）。 */
    fun hasRange(text: String): Boolean =
        RANGE_WITH_UNITS.containsMatchIn(text) || RANGE.containsMatchIn(text)

    /**
     * 全角数字 → 半角（只动 `０-９`，别的一律不碰）。
     *
     * 为什么在这里顺手做：全角数字的念法虽然也对，但同一句里混着半角与全角
     * （`气温８到 19 度`）会让 TTS 的断句听起来一顿一顿的；既然这一段本来就要替换掉，
     * 统一成半角是零风险的。**范围之外的全角数字不动**（那可能是原文，屏幕上要照旧）。
     */
    internal fun halfWidthDigits(s: String): String {
        if (s.none { it in '\uFF10'..'\uFF19' }) return s
        return buildString(s.length) {
            for (c in s) append(if (c in '\uFF10'..'\uFF19') '0' + (c - '\uFF10') else c)
        }
    }
}
