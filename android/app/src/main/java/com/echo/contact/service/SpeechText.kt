package com.echo.contact.service

/**
 * 念之前的**文本归一化**（只改"念出来的那串"，屏幕上的原文一个字都不动）。
 *
 * ## 为什么要有它（用户 2026-10-18 傍晚的原话）
 *
 * > *"朗读气温的时候 8-19 度，总被念成 819 度，这个有修复的可能吗"*
 *
 * 有 —— 而且问题不在数据、在**念法**：手机的系统 TTS（以及 ECHO 的 `/api/tts`）拿到
 * `8-19` 会把那个连字符当"负号 / 连接符"吞掉，于是"八到十九度"被念成"八百一十九度"。
 * 屏幕上该显示的还是 `8-19 度`（用户要看的也是它），只有**送去合成的那串**要换成
 * "8 到 19 度"。
 *
 * ## 规则边界（写死在 [RANGE] 里，`SpeechTextTest` 逐条钉住）
 *
 * 只有**同时**满足下面三条才改：
 *
 *  1. 左右各是一个**无符号**数字（整数或小数）：`8`、`8.5`；
 *  2. 中间是区间分隔符之一：`-`、`－`（全角）、`—`（破折号）、`–`（短破折号）、
 *     `~`、`～`（全角），两边可以有空格；
 *  3. 右数字**后面紧跟一个区间单位**（中间可有空格）：`度`、`℃`、`°C`、`°`、`%`、
 *     `km`、`公里`、`千米`。
 *
 * 第 ③ 条是"别过度归一化"的关键 —— 它把日期与版本号挡在外面（这些**故意不改**）：
 *
 *  * `10-18`、`2026-10-18`：后面没有单位，是**日期**；念成"10 到 18"反而是错的；
 *  * `v2.1.7`、`2.1.7`：根本没有区间分隔符；
 *  * `-5 度`、`最低-5度`：左边没有数字（负号不是数字）→ 不动；
 *    连 `-5-3度` 这种"负数区间"也不动（左数字紧跟 `-`，被 `(?<!...)` 挡住）：
 *    **宁可少改，也不要把零下温度念错**。
 *
 * ## 为什么只替换"左数字 分隔符 右数字"这一小段
 *
 * 单位**不消费**（只用作前瞻断言），所以 `8 - 19 ℃` → `8 到 19 ℃`：
 * 原来那个空格、单位、以及单位后面的字（"度左右"、"% 以上"）一个字节都不动。
 * 把单位一起吃掉再拼回去，迟早会把某种写法拼坏。
 *
 * ## 为什么必须幂等
 *
 * 调用点不止一处（界面朗读入口一次、系统 TTS 引擎入口再兜一次 —— 见那些地方的注释）。
 * 同一条文本被归一化两遍也只能得到同一个结果，绝不能出现"8 到 到 19"。
 * 这一点由 `SpeechTextTest` 用"套两遍 == 套一遍"钉住。
 */
internal object SpeechText {

    /**
     * 区间单位白名单（见类注释第 ③ 条）。
     *
     * `°C` 要写在 `°` 前面：虽然这里是前瞻（不消费），但短的那个先匹配会让
     * `8-19°C` 的 `C` 留在原文里 —— 结果其实一样，只是把长的写前面更不容易读错。
     */
    private const val RANGE_UNITS = "(?:度|℃|°C|°|%|公里|千米|[kK][mM])"

    /**
     * 「数字 + 分隔符 + 数字 +（紧跟单位）」。
     *
     *  * `(?<![\d.\-－—–~～])`：左数字**不许**紧跟在数字 / 小数点 / 各种连字符后面 ——
     *    这样 `2026-10-18`、`-5-3` 都不会被从中间切一刀；
     *  * `(?=\s*单位)`：单位只当前瞻、**不消费**，所以 `8 - 19 ℃` 里那个空格与单位原样留着。
     */
    private val RANGE = Regex(
        "(?<![\\d.\\-－—–~～])" +
            "(\\d+(?:\\.\\d+)?)" +
            "\\s*[-－—–~～]\\s*" +
            "(\\d+(?:\\.\\d+)?)" +
            "(?=\\s*" + RANGE_UNITS + ")"
    )

    /**
     * 把 [text] 里的数字区间换成"「到」"的念法；其余字节原样返回（**幂等**）。
     *
     * 空串原样返回（`Regex.replace` 对空串本来也无事，这里只是省一次构造）。
     */
    fun normalize(text: String): String =
        if (text.isEmpty()) text else RANGE.replace(text) { m ->
            "${m.groupValues[1]} 到 ${m.groupValues[2]}"
        }

    /** 这段文本里有没有"会被改"的区间（用例与排查用；只读，不改文本）。 */
    fun hasRange(text: String): Boolean = RANGE.containsMatchIn(text)
}
