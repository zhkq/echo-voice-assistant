# -*- coding: utf-8 -*-
"""speech_text.py — 念/合成之前的文本归一化。

## 为什么要有它（用户 2026-10-18 实测，电脑与手机同错）

用户原话：*"朗读气温的时候 8-19 度，总被念成 819 度，这个有修复的可能吗"*。

真实原文（`D:\\ECHO\\data\\echo.db` 的 `commands.reply`，不是猜的）::

    明天（10月19日，周一）北京天气晴转多云，气温 8~19℃，白天南风、夜间北风…

问题**不在数据、在念法**：TTS 拿到 `8~19` 会把那个区间分隔符（连字符/波浪号/短破折号）
当"连接符或负号"吞掉，于是"八到十九度"被念成"八百一十九度"。
所以修法是**只改送去合成的那串**，把分隔符换成口语里本来就有的"到"：

    8~19℃  →  8 到 19℃

`commands.reply`、界面、日志、事件里的 `speakText` 一律保持原文 —— 用户要看的也是原文
（这条口径与手机侧 `android/.../service/SpeechText.kt` 一致，那一条线已按它修好）。

## 规则边界（只在这三条**同时**成立时才改）

  1. 左右各是一个**无符号**数字（整数或小数）：`8`、`8.5`、`19.2`；
  2. 中间是区间分隔符之一：`-`、`－`（全角）、`—`（破折号）、`–`（短破折号）、`~`、`～`（全角），
     分隔符两边可有空格；
  3. 单位/量纲**在场**（见 `RANGE_UNITS`）：`℃` `度` `°C` `°` `％` `%` `hPa` `km` `公里`
     `千米` `公里/小时` `米` `级`。

第 ③ 条是"别过度归一化"的关键：**没有单位就不动**。这一条把下面这些全挡在外面（故意不改）：

  * `10-18`、`2026-10-18`、`（10-18 20:00发布）` —— **日期**，念成"10 到 18"反而是错的；
  * `18:00–19:30`、`5—8时` —— **时间**；
  * `v2.1.7`、`2.1.7` —— **版本号**（本来也没有区间分隔符）；
  * `-5℃`、`最低-5度` —— **负数**：左边没有"数字"，负号不是数字；
  * `-5-3℃` —— "负数区间"：左数字紧跟在 `-` 后面，被左守卫 `(?<![\\d.\\-－—–~～])` 挡住。
    **宁可少改，也不要把零下温度念错**；
  * `11—12 月`、`2—3 人`、`第8-19条` —— 单位不在白名单里（`月`/`人`/`条` 不进来）。

## 为什么单位只当"前瞻"、不消费

只替换 `左数字 + 分隔符 + 右数字` 这一小段，单位与其后的文字（`℃`、`"% 以上"`、`"度左右"`）
一个字节都不动，所以 `8 - 19 ℃` → `8 到 19 ℃`，空格也原样留着。
把单位一起吃进来再拼回去，迟早会把某种写法拼坏（`℃` 与 `°C`、`%` 与 `％` 的写法差异太多）。

## `1013–1017hPa` 为什么**要**改（这一条是我判断的，写清楚理由）

`hPa` 是百帕，`1013–1017hPa` 是**气压区间**，不是别的任何东西 —— 把分隔符吞掉念成
"1013 1017hPa"是错的，换成"1013 到 1017hPa"才对。它与日期/版本号的关键区别是
**它有单位**，这正是第 ③ 条想要的那种"确凿的区间"。所以 `hPa` 进白名单。

## 为什么必须幂等

这两条路都会到这里：电脑本机朗读（`tts.speak`）与手机/手表来要音频字节（`tts.synthesize`），
而手机自己也会先归一化一次（`SpeechText.kt`）。同一串被套两遍只能得到同一个结果，
绝不能出现"8 到 到 19" —— 替换之后分隔符就没了，所以第二遍自然不匹配（`test_pc_speech_text`
用"套两遍 == 套一遍"钉住）。
"""

import re

#: 区间单位白名单。**以真实数据为准**：`D:\\ECHO\\data\\echo.db` 的回复里实际出现的是
#: `℃`、`%`、`hPa`（`8~19℃`、`60%–78%`、`1013–1017hPa`）；`度`/`公里`/`级` 等是天气类
#: 回复的常见写法，一起收进来 —— 它们同样只在"两边都是无符号数字 + 紧跟单位"时才生效，
#: 所以不会比只写 `℃` 更容易误改（日期/时间/版本号没有这些单位跟着）。
#: 顺序：长的写前面（`公里/小时` 先于 `公里`，`°C` 先于 `°`），只影响匹配到的"最长那个"。
RANGE_UNITS = "公里/小时|公里|千米|hPa|°C|℃|°|度|%|％|km|米|级"

#: 左守卫：左数字**不许**紧跟在数字 / 小数点 / 各种连字符后面。
#: 这一条单独承担两件事：`2026-10-18` 不会被从中间切一刀，`-5-3℃` 这种负数区间也不动。
_LEFT_GUARD = r"(?<![\d.\-－—–~～])"
_NUM = r"\d+(?:\.\d+)?"
_SEP = r"\s*[-－—–~～]\s*"

#: ① 单位在**右边**（最常见：`8~19℃`、`1013–1017hPa`、`60-70公里/小时`）。
#:    单位只当前瞻（`(?=…)`），**不消费**。
_RANGE_RIGHT_UNIT = re.compile(
    _LEFT_GUARD + "(%s)" % _NUM + _SEP + "(%s)" % _NUM + r"(?=\s*(?:%s))" % RANGE_UNITS)

#: ② 单位在**两边**（真实数据里的 `60%–78%`：两个数字各自带 `%`）。
#:    单位用命名组 + 反向引用要求"两边是同一个单位"，`60%–78℃` 这种混写不动。
_RANGE_BOTH_UNITS = re.compile(
    _LEFT_GUARD + "(%s)" % _NUM
    + r"\s*(?P<u>%s)" % RANGE_UNITS + _SEP + "(%s)" % _NUM + r"\s*(?P=u)")


def normalize(text):
    """把数字区间换成"…到…"的念法；其余字节原样返回（**幂等**）。

    ``text`` 不是字符串（空串 / ``None`` / 别的）时**原样返回**：这里只做"念法"这件小事，
    不该在参数形态上抛异常（调用方已经各自做过空文本判断）。
    """
    if not isinstance(text, str) or not text:
        return text
    # 先跑"单位在右"（覆盖绝大多数），再跑"单位在两边"（`60%–78%`）。
    # 两条互不重叠：前者的分隔符必须紧跟在左数字后面，而"两边带单位"那里隔着个单位。
    out = _RANGE_RIGHT_UNIT.sub(lambda m: "%s 到 %s" % (m.group(1), m.group(2)), text)
    return _RANGE_BOTH_UNITS.sub(
        lambda m: "%s%s 到 %s%s" % (m.group(1), m.group("u"), m.group(3), m.group("u")), out)
